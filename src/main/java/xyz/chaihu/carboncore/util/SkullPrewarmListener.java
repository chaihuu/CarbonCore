package xyz.chaihu.carboncore.util;

import org.bukkit.entity.Player;
import org.bukkit.event.EventHandler;
import org.bukkit.event.EventPriority;
import org.bukkit.event.Listener;
import org.bukkit.event.player.PlayerJoinEvent;
import org.bukkit.plugin.Plugin;

/**
 * Prewarms the skull texture cache when a player joins (LiteSignIn strategy),
 * so head menus render the real skin on first open. Quit deliberately does not
 * evict: cached textures are reused across sessions.
 */
public final class SkullPrewarmListener implements Listener {

    private final Plugin plugin;

    public SkullPrewarmListener(Plugin plugin) {
        this.plugin = plugin;
    }

    @EventHandler(priority = EventPriority.MONITOR, ignoreCancelled = true)
    public void onJoin(PlayerJoinEvent event) {
        Player player = event.getPlayer();
        SkullTextureManager.refreshAsync(plugin, player.getUniqueId(), player.getName());
    }
}
